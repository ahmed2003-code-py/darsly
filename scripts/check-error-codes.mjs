#!/usr/bin/env node
/**
 * Every error code the API can send has words a person can read.
 *
 * The failure this guards against was found in production: a teacher adding a
 * guardian read "there is a conflict with existing data — check the data and
 * try again". The API had said exactly what was wrong (`PHONE_IN_USE`: the
 * number belongs to another account), but that code had no copy, so the web
 * fell back to the sentence for a bare HTTP 409. 165 of 346 codes were in the
 * same state when this check was written.
 *
 * A code thrown anywhere under apps/api/src passes when one of these holds:
 *
 *  1. `err.<key>` exists in BOTH ar.json and en.json, where <key> is the one
 *     errorMessage.ts derives (`PHONE_IN_USE` → `err.ePhoneInUse`);
 *  2. the web handles it itself — the code appears as a literal in web source
 *     (a feature with its own copy, like the paper-import warnings);
 *  3. it is a generic taxonomy code (api-error.ts GENERIC_CODE), which the web
 *     answers with its per-status sentence by design;
 *  4. it is on the allowlist below, with the reason no person can meet it.
 *
 * Field codes from the validation factory need `err.field.<CODE>` in both.
 *
 * Usage: node scripts/check-error-codes.mjs
 */
import { readFileSync, readdirSync, statSync } from 'node:fs';
import { join } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = fileURLToPath(new URL('../', import.meta.url));
const API = join(ROOT, 'apps/api/src');
const WEB = join(ROOT, 'apps/web/src');

/** Codes no person can meet through the UI. Each needs a reason. */
const NOT_USER_FACING = {
  SAVE50: 'a demo coupon code, not an error',
  WELCOME10: 'a demo coupon code, not an error',
  BAD_SEQ: 'classroom audio-chunk protocol, sent by the client code itself',
  BAD_AUDIO: 'classroom audio-chunk protocol',
  AUDIO_RATE: 'classroom audio-chunk protocol',
  EMPTY_AUDIO: 'classroom audio-chunk protocol',
  CAPTURE_OFF: 'classroom audio-chunk protocol; the client stops capturing',
  CURSOR_CONFLICT: 'chat paging parameters — a client bug, never a user action',
  DELETE_SCOPE: 'chat delete parameter — a client bug, never a user action',
  CLIENT_ID_INVALID: 'chat idempotency key format — generated by the client',
  RTC_TRACK_DENIED: 'WebRTC track negotiation — a client bug, never a user action',
  PAYOUT_UNSCOPED: 'ledger invariant — an internal defect, surfaced as such',
  RELEASE_EXCEEDS_HELD: 'ledger invariant — an internal defect, surfaced as such',
};

function walk(dir) {
  return readdirSync(dir).flatMap((name) => {
    const full = join(dir, name);
    if (statSync(full).isDirectory()) return walk(full);
    return /\.tsx?$/.test(name) && !/\.spec\.tsx?$/.test(name) ? [full] : [];
  });
}

const read = (f) => readFileSync(f, 'utf8');
const ar = JSON.parse(read(join(WEB, 'i18n/ar.json'))).err ?? {};
const en = JSON.parse(read(join(WEB, 'i18n/en.json'))).err ?? {};

// The same derivation errorMessage.ts uses; the explicit map mirrors its EXPLICIT.
const resolver = read(join(WEB, 'lib/errorMessage.ts'));
const explicit = Object.fromEntries(
  [
    ...(/const EXPLICIT[^{]*\{([\s\S]*?)\n\};/.exec(resolver)?.[1] ?? '').matchAll(
      /([A-Z_]+):\s*'err\.([\w.]+)'/g,
    ),
  ].map((m) => [m[1], m[2]]),
);
const keyFor = (code) =>
  explicit[code] ??
  'e' +
    code
      .toLowerCase()
      .replace(/_(.)/g, (_, c) => c.toUpperCase())
      .replace(/^(.)/, (_, c) => c.toUpperCase());
const has = (ns, key) =>
  key.split('.').reduce((o, k) => (o == null ? o : (o[k] ?? o[`${k}_other`])), ns) != null;

const generic = new Set(
  [...read(join(API, 'common/errors/api-error.ts')).matchAll(/\]: '([A-Z_]+)'/g)].map((m) => m[1]),
);
generic.add('VALIDATION_FAILED');

const factory = read(join(API, 'common/errors/validation-exception.factory.ts'));
const constraintMap = /const CONSTRAINT_CODE[^{]*\{([\s\S]*?)\n\};/.exec(factory)?.[1] ?? '';
const fieldCodes = new Set(
  [...constraintMap.matchAll(/:\s*'([A-Z_]+)'/g)]
    .map((m) => m[1])
    .concat(['INVALID', 'INVALID_PHONE', 'WEAK_PASSWORD']),
);

const webText = walk(WEB).map(read).join('\n');
const codes = new Map();
for (const file of walk(API)) {
  if (file.includes('validation-exception.factory')) continue;
  for (const m of read(file).matchAll(/code:\s*['"`]([A-Z][A-Z0-9_]{2,})['"`]/g)) {
    if (!codes.has(m[1])) codes.set(m[1], file.replace(ROOT, ''));
  }
}

const fail = [];
let copied = 0;
for (const [code, where] of [...codes].sort()) {
  const key = keyFor(code);
  if (has(ar, key) && has(en, key)) {
    copied++;
    continue;
  }
  if (has(ar, key) !== has(en, key)) {
    fail.push(`${code}: err.${key} exists in ${has(ar, key) ? 'ar' : 'en'} only (${where})`);
    continue;
  }
  if (generic.has(code) || NOT_USER_FACING[code]) continue;
  if (new RegExp(`['"\`]${code}['"\`]|\\b${code}:`).test(webText)) continue;
  fail.push(`${code}: no copy — add err.${key} to ar.json and en.json (${where})`);
}
for (const code of fieldCodes) {
  for (const [name, ns] of [
    ['ar', ar],
    ['en', en],
  ])
    if (!has(ns, `field.${code}`))
      fail.push(`field code ${code}: err.field.${code} missing in ${name}`);
}

if (fail.length) {
  console.error(`✗ ${fail.length} error code(s) without words:`);
  for (const f of fail) console.error(`   ${f}`);
  process.exit(1);
}
console.log(
  `✓ ${codes.size} API error codes — ${copied} with their own copy, the rest generic, ` +
    `handled by their feature, or not user-facing; ${fieldCodes.size} field codes`,
);
